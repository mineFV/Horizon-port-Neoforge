package org.joml;

/** The stand-in for JOML's Matrix3fc: a 3x3 matrix of floats, read only (its elements, column then row). */
public interface Matrix3fc {
    float m00();

    float m01();

    float m02();

    float m10();

    float m11();

    float m12();

    float m20();

    float m21();

    float m22();
}
